import { chromium } from 'playwright';
import { dirname, join } from 'node:path';
import { mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root=join(dirname(fileURLToPath(import.meta.url)), '..'), output=join(root,'out/reference-integration');
mkdirSync(output,{recursive:true});
import { spawn } from 'node:child_process';
import assert from 'node:assert/strict';
const base=process.env.NV_API_URL || 'http://127.0.0.1:8787';
if (!['127.0.0.1','localhost'].includes(new URL(base).hostname)) throw new Error('UI smoke checks must use a local development server.');
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:1440,height:1000},colorScheme:'light'}),page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
let id,jobId;
try {
 await page.goto(base,{waitUntil:'networkidle'});
 await page.evaluate(async()=>{await api('/api/auth/dev',{method:'POST',body:{consent:true,email:'ui-'+Date.now()+'@localhost'}});});
 await page.reload({waitUntil:'networkidle'});
 await page.goto(base+'/#/admin/zalo',{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:'Hộp thư Zalo'}).waitFor();
 await page.screenshot({path:join(output,'admin-zalo.png'),fullPage:true});
 await page.getByRole('button',{name:'Tải lại hộp thư'}).click();
 await page.goto(base+'/#/admin/may-dung',{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:'Máy dựng và hàng đợi'}).waitFor();
 await page.screenshot({path:join(output,'admin-renders.png'),fullPage:true});
 const made=await page.evaluate(async()=>api('/api/projects/generate',{method:'POST',body:{source:'mine-free',topic:Array.from({length:8},(_,i)=>`Bước ${i+1}: dành hai phút để đọc một trang sách và bắt đầu thói quen nhỏ. Bạn có thể làm ngay hôm nay, không cần chờ đến lúc rảnh.`).join('\n\n'),voiceId:'free-female',style:'whiteboard',intro:false,mode:'hand'}}));
 id=made.id;
 const r=await page.evaluate(async id=>api(`/api/projects/${id}/render`,{method:'POST'}),id);jobId=r.job.id;
 await page.goto(base+'/#/p/'+id,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Mở bàn dựng'}).first().click();
 await page.getByRole('dialog').waitFor();
 const child=spawn(process.execPath,['--env-file='+join(root,'web/.dev.vars'),'--input-type=module','-e','process.env.RUNNER_TTS="mock";process.argv.push("--once");await import("./src/cli/runner.ts")'],{cwd:root,env:{...process.env,NV_API_URL:base},stdio:['ignore','pipe','pipe']});
 const childDone=new Promise((resolve,reject)=>{let log='';child.stderr.on('data',d=>log+=d);child.on('exit',code=>code===0?resolve():reject(new Error(log)));});
 await page.waitForFunction(()=>document.querySelector('dialog.render-desk .active')?.textContent.includes('Dựng video'),{},{timeout:90000});
 await page.screenshot({path:join(output,'render-desk-desktop.png')});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:join(output,'render-desk-mobile.png')});
 const width=await page.getByRole('dialog').evaluate(el=>({width:el.getBoundingClientRect().width,client:innerWidth}));assert.ok(width.width<=width.client);
 await childDone;
 await page.getByRole('heading',{name:'Video đã sẵn sàng',exact:true}).waitFor({timeout:20000});
 await page.getByRole('dialog').getByRole('link',{name:'Tải MP4'}).waitFor();
 await page.screenshot({path:join(output,'render-desk-done.png')});
 await page.getByRole('button',{name:'Đóng bàn dựng'}).click();assert.equal(await page.getByRole('dialog').count(),0);
 assert.deepEqual(errors,[]);
 console.log('PASS browser: admin Zalo inbox, render operations desk, live rendering phases, responsive dialog, result downloads and close. No JavaScript page errors.');
}finally{
 if(id)await page.evaluate(async id=>api('/api/projects/'+id,{method:'DELETE'}),id).catch(()=>{});
 await browser.close();
}
